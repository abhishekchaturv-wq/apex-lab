"""Reproducible baseline predictive analysis pipeline."""

from __future__ import annotations

import argparse
import json
import subprocess
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np
import polars as pl
from sklearn.metrics import precision_score, recall_score

from apex_lab.dataset import DatasetBuildConfig, DatasetBuilder, build_metadata
from apex_lab.models.trainer import MODEL_REGISTRY, train_baseline_model

REQUIRED_RAW_COLUMNS = {"timestamp", "open", "high", "low", "close", "volume"}
TARGET_DEFINITIONS = {
    "top": ("TOP", "target_top"),
    "bottom": ("BOTTOM", "target_bottom"),
}
DEFAULT_THRESHOLDS = (0.50, 0.60, 0.70, 0.80, 0.90)


@dataclass(frozen=True)
class BaselineAnalysisResult:
    """Paths and metadata generated by a baseline predictive analysis run."""

    reports_dir: Path
    dataset_id: str
    models_trained: int
    symbols_processed: list[str]


def run_baseline_predictive_analysis(
    *,
    input_dir: Path,
    output_dir: Path = Path("reports"),
    timeframe: str = "30m",
    feature_version: str = "features-v1",
    label_version: str = "labels-v1",
    thresholds: tuple[float, ...] = DEFAULT_THRESHOLDS,
    random_state: int = 42,
    test_size: float = 0.2,
) -> BaselineAnalysisResult:
    """Run the end-to-end baseline predictive analysis and export reports."""
    raw_by_symbol = _load_historical_data(input_dir)
    git_sha = _git_sha()
    builder = DatasetBuilder()

    per_symbol_datasets: list[pl.DataFrame] = []
    symbols = sorted(raw_by_symbol)
    for symbol in symbols:
        build_config = DatasetBuildConfig(
            symbols=[symbol],
            timeframe=timeframe,
            feature_version=feature_version,
            label_version=label_version,
            git_sha=git_sha,
        )
        result = builder.build(raw_by_symbol[symbol], build_config)
        per_symbol_datasets.append(result.dataset.with_columns(pl.lit(symbol).alias("symbol")))

    combined_dataset = pl.concat(per_symbol_datasets, how="vertical")
    metadata = build_metadata(
        combined_dataset,
        feature_version=feature_version,
        label_version=label_version,
        symbols=symbols,
        timeframe=timeframe,
        git_sha=git_sha,
    )

    modeling_dataset = combined_dataset.with_columns(
        [
            (pl.col("label") == target_label).cast(pl.Int8).alias(target_column)
            for target_label, target_column in TARGET_DEFINITIONS.values()
        ]
    )
    feature_columns = _select_model_feature_columns(modeling_dataset)

    runs: list[dict[str, Any]] = []
    threshold_rows: list[dict[str, Any]] = []
    confusion_rows: list[dict[str, Any]] = []
    calibration_rows: list[dict[str, Any]] = []
    probability_rows: list[dict[str, Any]] = []
    all_importance_frames: list[pl.DataFrame] = []

    for model_name in sorted(MODEL_REGISTRY):
        for target_name, (_, target_column) in TARGET_DEFINITIONS.items():
            train_frame = modeling_dataset.select(feature_columns + [target_column])
            training_result = train_baseline_model(
                train_frame,
                target_column=target_column,
                model_name=model_name,
                test_size=test_size,
                random_state=random_state,
            )

            metrics = training_result.metrics
            runs.append(
                {
                    "model": model_name,
                    "target": target_name,
                    "metrics": metrics,
                    "hyperparameters": _extract_hyperparameters(training_result.model),
                    "error_analysis": _error_analysis_summary(training_result.prediction_probabilities),
                }
            )

            threshold_rows.extend(
                _build_threshold_rows(
                    model_name=model_name,
                    target_name=target_name,
                    probabilities=training_result.prediction_probabilities,
                    thresholds=thresholds,
                )
            )

            confusion_rows.append(
                _build_confusion_row(model_name=model_name, target_name=target_name, metrics=metrics)
            )
            calibration_rows.extend(
                _build_calibration_rows(model_name=model_name, target_name=target_name, metrics=metrics)
            )
            probability_rows.extend(
                _build_probability_distribution_rows(
                    model_name=model_name,
                    target_name=target_name,
                    probabilities=training_result.prediction_probabilities,
                )
            )

            all_importance_frames.append(
                training_result.feature_importance.with_columns(
                    pl.lit(model_name).alias("model"),
                    pl.lit(target_name).alias("target"),
                )
            )

    importance_table = _aggregate_feature_importance(all_importance_frames)
    correlation_table = _build_feature_correlation_table(modeling_dataset, feature_columns)

    reports_dir = output_dir
    reports_dir.mkdir(parents=True, exist_ok=True)

    training_timestamp = datetime.now(tz=UTC).isoformat()

    metrics_payload = {
        "dataset_id": metadata.dataset_id,
        "symbols": symbols,
        "timeframe": timeframe,
        "training_timestamp": training_timestamp,
        "runs": runs,
    }
    (reports_dir / "metrics.json").write_text(json.dumps(metrics_payload, indent=2), encoding="utf-8")
    importance_table.write_csv(reports_dir / "feature_importance.csv")
    pl.DataFrame(threshold_rows).write_csv(reports_dir / "threshold_analysis.csv")
    pl.DataFrame(confusion_rows).write_csv(reports_dir / "confusion_matrix.csv")
    pl.DataFrame(calibration_rows).write_csv(reports_dir / "calibration.csv")
    pl.DataFrame(probability_rows).write_csv(reports_dir / "probability_distribution.csv")
    correlation_table.write_csv(reports_dir / "feature_correlation.csv")

    experiment_payload = {
        "dataset_id": metadata.dataset_id,
        "git_sha": git_sha,
        "model": sorted(MODEL_REGISTRY),
        "hyperparameters": {
            run["model"] + "_" + run["target"]: run["hyperparameters"] for run in runs
        },
        "feature_version": feature_version,
        "label_version": label_version,
        "training_timestamp": training_timestamp,
        "metrics": {run["model"] + "_" + run["target"]: run["metrics"] for run in runs},
    }
    (reports_dir / "experiment.json").write_text(json.dumps(experiment_payload, indent=2), encoding="utf-8")

    return BaselineAnalysisResult(
        reports_dir=reports_dir,
        dataset_id=metadata.dataset_id,
        models_trained=len(runs),
        symbols_processed=symbols,
    )


def main(argv: list[str] | None = None) -> int:
    """CLI entrypoint for reproducible baseline predictive analysis."""
    parser = argparse.ArgumentParser(description="Run baseline predictive analysis and export reports.")
    parser.add_argument("--input-dir", type=Path, required=True, help="Directory of historical CSV/Parquet files.")
    parser.add_argument("--output-dir", type=Path, default=Path("reports"), help="Reports output directory.")
    parser.add_argument("--timeframe", type=str, default="30m", help="Dataset timeframe label.")
    parser.add_argument("--feature-version", type=str, default="features-v1", help="Feature pipeline version.")
    parser.add_argument("--label-version", type=str, default="labels-v1", help="Label pipeline version.")
    args = parser.parse_args(argv)

    run_baseline_predictive_analysis(
        input_dir=args.input_dir,
        output_dir=args.output_dir,
        timeframe=args.timeframe,
        feature_version=args.feature_version,
        label_version=args.label_version,
    )
    return 0


def _load_historical_data(input_dir: Path) -> dict[str, pl.DataFrame]:
    """Load raw OHLCV files keyed by symbol."""
    files = sorted(input_dir.glob("*.csv")) + sorted(input_dir.glob("*.parquet"))
    if not files:
        raise ValueError(f"No historical files found in '{input_dir}'")

    by_symbol: dict[str, pl.DataFrame] = {}
    for path in files:
        frame = _read_raw_frame(path)
        symbol = path.stem.upper()
        if "symbol" in frame.columns:
            symbol = str(frame["symbol"][0]).upper()
        _validate_raw_columns(frame, path)
        normalized = _normalize_timestamp(frame).sort("timestamp")
        by_symbol[symbol] = normalized
    return by_symbol


def _read_raw_frame(path: Path) -> pl.DataFrame:
    """Read a raw OHLCV file using format-aware Polars readers."""
    if path.suffix.lower() == ".csv":
        return pl.read_csv(path, try_parse_dates=True)
    if path.suffix.lower() == ".parquet":
        return pl.read_parquet(path)
    raise ValueError(f"Unsupported file format: {path}")


def _validate_raw_columns(frame: pl.DataFrame, path: Path) -> None:
    """Validate required OHLCV columns for baseline analysis."""
    missing = sorted(REQUIRED_RAW_COLUMNS.difference(frame.columns))
    if missing:
        raise ValueError(f"Missing required columns {missing} in {path}")


def _normalize_timestamp(frame: pl.DataFrame) -> pl.DataFrame:
    """Cast timestamp into datetime if loaded as strings."""
    if frame.schema.get("timestamp") == pl.Utf8:
        return frame.with_columns(
            pl.col("timestamp").str.strptime(pl.Datetime, strict=False).alias("timestamp")
        )
    return frame


def _select_model_feature_columns(dataset: pl.DataFrame) -> list[str]:
    """Return numeric feature columns excluding labels and metadata."""
    excluded = {
        "timestamp",
        "symbol",
        "label",
        "confidence",
        "future_return",
        "bars_to_target",
        "bars_to_failure",
        "target_top",
        "target_bottom",
    }
    numeric_dtypes = {
        pl.Int8,
        pl.Int16,
        pl.Int32,
        pl.Int64,
        pl.UInt8,
        pl.UInt16,
        pl.UInt32,
        pl.UInt64,
        pl.Float32,
        pl.Float64,
    }
    return [
        column
        for column, dtype in dataset.schema.items()
        if column not in excluded and dtype in numeric_dtypes
    ]


def _build_threshold_rows(
    *,
    model_name: str,
    target_name: str,
    probabilities: pl.DataFrame,
    thresholds: tuple[float, ...],
) -> list[dict[str, Any]]:
    """Compute threshold-level precision/recall/signal statistics."""
    y_true = probabilities["y_true"].to_numpy()
    y_prob = probabilities["probability"].to_numpy()
    rows: list[dict[str, Any]] = []
    for threshold in thresholds:
        y_pred = (y_prob >= threshold).astype(int)
        rows.append(
            {
                "model": model_name,
                "target": target_name,
                "threshold": threshold,
                "precision": float(precision_score(y_true, y_pred, zero_division=0)),
                "recall": float(recall_score(y_true, y_pred, zero_division=0)),
                "number_of_signals": int(y_pred.sum()),
            }
        )
    return rows


def _build_confusion_row(*, model_name: str, target_name: str, metrics: dict[str, Any]) -> dict[str, Any]:
    """Build one confusion matrix row from nested metric payload."""
    matrix = metrics["confusion_matrix"]
    return {
        "model": model_name,
        "target": target_name,
        "tn": matrix[0][0],
        "fp": matrix[0][1],
        "fn": matrix[1][0],
        "tp": matrix[1][1],
    }


def _build_calibration_rows(
    *,
    model_name: str,
    target_name: str,
    metrics: dict[str, Any],
) -> list[dict[str, Any]]:
    """Flatten calibration curve arrays into tabular rows."""
    calibration = metrics["calibration"]
    mean_pred = calibration["curve"]["mean_predicted_probability"]
    frac_pos = calibration["curve"]["fraction_of_positives"]
    rows: list[dict[str, Any]] = []
    for idx, (mean_probability, fraction_positive) in enumerate(zip(mean_pred, frac_pos, strict=False)):
        rows.append(
            {
                "model": model_name,
                "target": target_name,
                "bin": idx,
                "mean_predicted_probability": mean_probability,
                "fraction_of_positives": fraction_positive,
                "brier_score": calibration["brier_score"],
            }
        )
    return rows


def _build_probability_distribution_rows(
    *,
    model_name: str,
    target_name: str,
    probabilities: pl.DataFrame,
    bins: int = 20,
) -> list[dict[str, Any]]:
    """Create probability distribution histogram rows for each class."""
    rows: list[dict[str, Any]] = []
    for class_value in [0, 1]:
        class_probs = probabilities.filter(pl.col("y_true") == class_value)["probability"].to_numpy()
        counts, edges = np.histogram(class_probs, bins=bins, range=(0.0, 1.0))
        for idx, count in enumerate(counts):
            rows.append(
                {
                    "model": model_name,
                    "target": target_name,
                    "class_value": class_value,
                    "bin_start": float(edges[idx]),
                    "bin_end": float(edges[idx + 1]),
                    "count": int(count),
                }
            )
    return rows


def _aggregate_feature_importance(frames: list[pl.DataFrame]) -> pl.DataFrame:
    """Aggregate feature importance across all model-target runs and export top 30."""
    merged = pl.concat(frames, how="vertical")
    aggregated = (
        merged.group_by("feature")
        .agg(
            [
                pl.col("permutation_importance_mean").mean().alias("permutation_importance_mean"),
                pl.col("model_importance").mean().alias("tree_importance"),
            ]
        )
        .sort("permutation_importance_mean", descending=True)
        .with_row_index(name="rank", offset=1)
    )
    return aggregated.head(30)


def _build_feature_correlation_table(dataset: pl.DataFrame, feature_columns: list[str]) -> pl.DataFrame:
    """Build pairwise feature correlation table and removal recommendations."""
    rows: list[dict[str, Any]] = []
    for idx, left_feature in enumerate(feature_columns):
        left_series = dataset[left_feature].to_numpy()
        left_std = float(np.std(left_series))
        for right_feature in feature_columns[idx + 1 :]:
            right_series = dataset[right_feature].to_numpy()
            right_std = float(np.std(right_series))
            if left_std == 0.0 or right_std == 0.0:
                correlation = 0.0
            else:
                correlation = float(np.corrcoef(left_series, right_series)[0, 1])
                if np.isnan(correlation):
                    correlation = 0.0
            rows.append(
                {
                    "feature_left": left_feature,
                    "feature_right": right_feature,
                    "correlation": correlation,
                    "abs_correlation": abs(correlation),
                    "candidate_for_removal": abs(correlation) >= 0.90,
                }
            )
    return pl.DataFrame(rows).sort("abs_correlation", descending=True)


def _extract_hyperparameters(model: object) -> dict[str, Any]:
    """Extract serializable hyperparameters from estimator or pipeline."""
    estimator = _unwrap_estimator(model)
    if not hasattr(estimator, "get_params"):
        return {}
    params = estimator.get_params(deep=False)
    serializable: dict[str, Any] = {}
    for key, value in params.items():
        if isinstance(value, (str, int, float, bool)) or value is None:
            serializable[key] = value
    return serializable


def _unwrap_estimator(model: object) -> object:
    """Extract inner estimator when model is a sklearn Pipeline."""
    if hasattr(model, "named_steps"):
        steps = model.named_steps
        if "model" in steps:
            return steps["model"]
        last_name = next(reversed(steps))
        return steps[last_name]
    return model


def _error_analysis_summary(probabilities: pl.DataFrame) -> dict[str, Any]:
    """Summarize false and missed signal characteristics from model probabilities."""
    false_predictions = probabilities.filter((pl.col("y_true") == 0) & (pl.col("y_pred") == 1))
    missed_predictions = probabilities.filter((pl.col("y_true") == 1) & (pl.col("y_pred") == 0))
    return {
        "false_signals": _probability_characteristics(false_predictions),
        "missed_signals": _probability_characteristics(missed_predictions),
    }


def _probability_characteristics(frame: pl.DataFrame) -> dict[str, Any]:
    """Compute aggregate probability characteristics for an error subset."""
    if len(frame) == 0:
        return {
            "count": 0,
            "mean_probability": None,
            "median_probability": None,
            "p90_probability": None,
        }
    return {
        "count": len(frame),
        "mean_probability": float(frame["probability"].mean()),
        "median_probability": float(frame["probability"].median()),
        "p90_probability": float(frame["probability"].quantile(0.9)),
    }


def _git_sha() -> str | None:
    """Return current git SHA when available."""
    try:
        output = subprocess.check_output(["git", "rev-parse", "HEAD"], text=True, timeout=5).strip()
        return output or None
    except (subprocess.SubprocessError, FileNotFoundError):
        return None


if __name__ == "__main__":
    raise SystemExit(main())
